/** Яндекс.Метрика. Сам счётчик инициализируется инлайн-сниппетом в `index.html` (он должен
 *  стартовать до бандла), здесь — только докладывание просмотров при SPA-навигации.
 *
 *  Метрика автоматически считает ОДИН просмотр — тот, на котором загрузился документ.
 *  Переходы react-router (URL меняется через history.pushState, страница не перезагружается)
 *  счётчик сам не видит, поэтому на каждую смену адреса шлём `ym('hit')` с явным referer
 *  (предыдущим URL) — иначе в отчётах виден только вход и отчёт «Страницы входа/выхода»
 *  лишён смысла. */

/** ID счётчика — тот же, что в сниппете `index.html`; при смене менять в обоих местах. */
const COUNTER_ID = 112655118

type YmFn = (id: number, action: string, ...args: unknown[]) => void

declare global {
  interface Window {
    ym?: YmFn
  }
}

/** Просмотр страницы при SPA-переходе. `url`/`referer` — абсолютные адреса. */
export function metrikaHit(url: string, referer?: string): void {
  // Сниппет определяет `window.ym` синхронно (очередь до загрузки tag.js), но при
  // заблокированном/вырезанном счётчике его не будет — молча выходим.
  window.ym?.(COUNTER_ID, 'hit', url, referer ? { referer } : undefined)
}
