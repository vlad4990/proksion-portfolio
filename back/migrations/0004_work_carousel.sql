-- 0004_work_carousel — флаг «карусель» для десктопной модалки работы.
-- По умолчанию картинки работы идут вертикальной лентой; у работ, где картинки после
-- главной сильно ниже её (лента делает их мелкими — ширину задаёт первая картинка),
-- админ может включить горизонтальную псевдо-карусель: центральный слайд + соседние
-- в градиентном блюре у краёв экрана. Мобилка флаг игнорирует (там лента ок).
-- SQLite без BOOLEAN: 0/1 + CHECK. Только ADD COLUMN — down-миграций нет.

ALTER TABLE work ADD COLUMN carousel INTEGER NOT NULL DEFAULT 0
  CHECK (carousel IN (0, 1));
