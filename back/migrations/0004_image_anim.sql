-- 0004_image_anim — носитель анимации у картинки (GIF / анимированный WebP).
-- NULL — картинка статичная (прежнее поведение, дефолт для всех существующих строк).
-- 'webp' — кадры лежат в webp-вариантах (thumb и full).
-- 'gif'  — full-анимация осталась оригинальным GIF'ом под ключом `{key_base}/full.gif`
--          (webp вышел тяжелее оригинала либо лента длиннее бюджета перекодирования);
--          thumb.webp анимирован и в этом случае.
-- AVIF анимацию не несёт никогда (libheif кодирует один кадр) — поэтому фронт у таких
-- картинок не предлагает avif-источник, иначе браузер молча выбрал бы статику.
-- Только ADD COLUMN — down-миграций нет.

ALTER TABLE image ADD COLUMN anim TEXT
  CHECK (anim IS NULL OR anim IN ('webp', 'gif'));
